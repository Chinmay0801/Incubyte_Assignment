/** Normalize make and model into a slug identifier */
export function getCarSlug(make: string, model: string): string {
  const norm = `${make} ${model}`
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

  if (norm.includes('swift')) return 'maruti-swift';
  if (norm.includes('i20')) return 'hyundai-i20';
  if (norm.includes('nexon')) return 'tata-nexon';
  if (norm.includes('punch')) return 'tata-punch-ev';
  if (norm.includes('slavia')) return 'skoda-slavia';
  if (norm.includes('seltos')) return 'kia-seltos';
  if (norm.includes('creta')) return 'hyundai-creta';
  if (norm.includes('thar')) return 'mahindra-thar';
  if (norm.includes('virtus')) return 'volkswagen-virtus';
  if (norm.includes('city')) return 'honda-city';
  if (norm.includes('xuv700')) return 'mahindra-xuv700';
  if (norm.includes('windsor')) return 'mg-windsor-ev';
  if (norm.includes('curvv')) return 'tata-curvv-ev';
  if (norm.includes('be-6') || norm.includes('be6')) return 'mahindra-be-6';
  if (norm.includes('innova') || norm.includes('hycross')) return 'toyota-innova-hycross';
  if (norm.includes('harrier')) return 'tata-harrier-ev';
  if (norm.includes('fortuner')) return 'toyota-fortuner';
  if (norm.includes('sealion')) return 'byd-sealion-7';
  if (norm.includes('seal')) return 'byd-seal';
  if (norm.includes('cyberster')) return 'mg-cyberster';

  return norm;
}

/** Retrieve all available gallery images for a vehicle, falling back to its main image */
export function getCarGallery(make: string, model: string, defaultImage?: string): string[] {
  const slug = getCarSlug(make, model);
  const found = CAR_GALLERIES[slug];
  if (found && found.length > 0) {
    return found;
  }
  return defaultImage ? [defaultImage] : [];
}
